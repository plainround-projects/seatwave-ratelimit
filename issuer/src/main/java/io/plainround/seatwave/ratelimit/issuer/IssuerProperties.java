package io.plainround.seatwave.ratelimit.issuer;

import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import java.nio.file.Path;
import java.time.Duration;
import org.springframework.boot.context.properties.ConfigurationProperties;
import org.springframework.validation.annotation.Validated;

/**
 * The issuer's settings, bound from {@code seatwave.issuer.*} and checked at start-up.
 *
 * @param issuer the {@code iss} it writes into every token
 * @param audience the {@code aud} it writes into every token
 * @param tokenLifetime how long a token is valid; Section 7's brief says 15 minutes
 * @param keyFile the private key set, generated by {@link KeyRingCli} into an ignored folder
 */
@Validated
@ConfigurationProperties("seatwave.issuer")
public record IssuerProperties(
    @NotNull @Pattern(regexp = "https?://[A-Za-z0-9.:-]{1,200}") String issuer,
    @NotNull @Pattern(regexp = "[a-z0-9-]{1,64}") String audience,
    @NotNull Duration tokenLifetime,
    @NotNull Path keyFile) {

  // An access token that lives longer than an hour is a bearer credential nobody can take back.
  private static final Duration MAX_LIFETIME = Duration.ofHours(1);

  /**
   * The lifetime must be positive and at most an hour; a missing one has its own problem line.
   *
   * @return true when the lifetime is inside that range or missing
   */
  @AssertTrue(message = "tokenLifetime must be more than 0 and at most 1h")
  public boolean isLifetimeInRange() {
    return tokenLifetime == null
        || (tokenLifetime.isPositive() && tokenLifetime.compareTo(MAX_LIFETIME) <= 0);
  }
}
